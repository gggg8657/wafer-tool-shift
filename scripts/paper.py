def load(run_dir="runs"):
    cells = {}
    for p in sorted(Path(run_dir).glob("*.json")):
        r = json.loads(p.read_text())
        if isinstance(r, dict) and {"protocol", "encoder", "objective"} <= set(r):
            cells.setdefault((r["protocol"], r["encoder"], r["objective"],
                              r.get("tag", "")), {})[r.get("seed", 0)] = r
    return cells


def stat(cells, key, field=("test", "macro_f1")):
    v = cells.get(key)
    if not v:
        return None
    xs = []
    for r in v.values():
        x = r
        for f in field:
            x = x.get(f) if isinstance(x, dict) else None
            if x is None:
                break
        if x is not None:
            xs.append(float(x))
    if not xs:
        return None
    return {"mean": sum(xs) / len(xs), "hr": (max(xs) - min(xs)) / 2,
            "n": len(xs), "vals": sorted(xs)}


def verdict(s, base, floor):
    """Does this cell differ from its baseline? Ranges disjoint AND margin
    above the pipeline's own run-to-run floor. Anything else is not a result."""
    if not s or not base or s["n"] < 2 or base["n"] < 2:
        return "no error bar"
    xs, bs = s["vals"], base["vals"]
    if min(xs) > max(bs):
        m = min(xs) - max(bs)
    elif min(bs) > max(xs):
        m = -(min(bs) - max(xs))
    else:
        return "overlaps ERM"
    if floor is None:
        return f"disjoint by {abs(m):.4f}"
    return ("**clears the floor**" if abs(m) > floor
            else f"below the floor ({abs(m):.4f} < {floor:.4f})")


def fmt(s, n=4):
    if s is None:
        return NM
    if s["n"] == 1:
        return f"{s['mean']:.{n}f}"
    return f"{s['mean']:.{n}f} ±{s['hr']:.{n}f} (n={s['n']})"


def table(rows, header):
    out = ["| " + " | ".join(str(h) for h in header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


